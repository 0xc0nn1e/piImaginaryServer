const messages: Record<Locale, Record<TranslationKey, string>> = {
  ja,
  "zh-HK": zhHK,
};

type Replacements = Record<string, string | number>;

export function getStoredLocale(): Locale {
  try {
    return window.localStorage.getItem(STORAGE_KEY) === "zh-HK" ? "zh-HK" : "ja";
  } catch {
    return "ja";
  }
}

export function translate(
  locale: Locale,
  key: TranslationKey,
  replacements: Replacements = {},
): string {
  return Object.entries(replacements).reduce(
    (value, [name, replacement]) => value.replaceAll(`{${name}}`, String(replacement)),
    messages[locale][key],
  );
}

interface I18nContextValue {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: TranslationKey, replacements?: Replacements) => string;
}

const I18nContext = createContext<I18nContextValue | null>(null);

export function LanguageProvider({ children }: PropsWithChildren) {
  const [locale, setLocaleState] = useState<Locale>(getStoredLocale);

  const setLocale = useCallback((nextLocale: Locale) => {
    setLocaleState(nextLocale);
    try {
      window.localStorage.setItem(STORAGE_KEY, nextLocale);
    } catch {
      // A blocked preference store should not prevent the UI from switching language.
    }
  }, []);

  const t = useCallback(
    (key: TranslationKey, replacements?: Replacements) =>
      translate(locale, key, replacements),
    [locale],
  );

  useEffect(() => {
    document.documentElement.lang = locale;
    document.title = "Wave Archive";
    document
      .querySelector('meta[name="description"]')
      ?.setAttribute("content", t("meta.description"));
  }, [locale, t]);

  const value = useMemo(() => ({ locale, setLocale, t }), [locale, setLocale, t]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  const context = useContext(I18nContext);
  if (!context) throw new Error("useI18n must be used inside LanguageProvider");
  return context;
}

export function statusLabelKey(status: string): TranslationKey {
  return `status.${status}` as TranslationKey;
}

export function stageLabelKey(stage: string): TranslationKey {
  return `stage.${stage}` as TranslationKey;
}

export function activityLabelKey(eventType: string): TranslationKey {
  const key = `detail.activity.${eventType}` as TranslationKey;
  return key in ja ? key : "detail.activity.unknown";
}
